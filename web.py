@app.get("/", response_class=HTMLResponse)
async def root(request: Request,
               token: str = Query(default=""),
               cortex_session: str = Cookie(default=""),
               _pub=Depends(_public_endpoint)):
    # Handles its own auth flow, exchanging ?token= for a session cookie; marked
    # public so the invariant test permits the inline check below.
    if not AUTH_TOKEN:
        return HTMLResponse(HTML)
    # Cookie carries a session id — verify against the session table.
    if cortex_session and _session_manager.check(cortex_session):
        return HTMLResponse(HTML)
    # guard the bootstrap path before validating so an attacker
    # who pounds /?token=<guess> can't probe at wire speed.
    ip = _client_ip(request)
    # First load carries ?token= from the terminal link; it is exchanged for a
    # session cookie and redirected to a clean "/".
    if token and _check_auth(token):
        is_https = _is_request_https(request)
        session_id = _session_manager.mint()
        resp = RedirectResponse(url="/", status_code=303)
        resp.set_cookie(
            key=AUTH_COOKIE_NAME,
            value=session_id,
            httponly=True,            # JS can't read it — XSS can't exfil
            secure=is_https,          # only over TLS when TLS is in play
            samesite="strict",        # CSRF: no cross-site submissions
            max_age=60 * 60 * 8,      # 8h working session; re-bootstrap after
            path="/",
        )
        return resp
    # No valid token anywhere — refuse with 401 rather than leaking the HTML.
    over = _note_auth_fail(ip)
    if over:
        # 429 stalls the attacker without leaking which token length they
        # got close on. Clients that legitimately hit this can wait 60s.
        raise HTTPException(status_code=429, detail="Too many auth failures")
    raise HTTPException(status_code=401, detail="Invalid or missing token")

@app.post("/api/logout")
async def logout(request: Request,
                 cortex_session: str = Cookie(default=""),
                 _pub=Depends(_public_endpoint)):
    # Unauthenticated on purpose: logging out of an expired session must still clear
    # the cookie.
    """end the current session. Removes the session id from the
    in-memory table so a stolen cookie stops working immediately. No
    auth required beyond presenting a cookie — unauthenticated POSTs
    just noop. Clears the cookie on the client side too."""
    if cortex_session:
        _session_manager.revoke(cortex_session)
    resp = Response(status_code=204)
    resp.delete_cookie(key=AUTH_COOKIE_NAME, path="/")
    return resp


@app.websocket("/ws")
async def ws_endpoint(ws: WebSocket,
                     token: str = Query(default=""),
                     _pub=Depends(_public_endpoint)):
    # Depends does not fire on websocket routes, so auth happens inline and again per
    # message. A missing Origin is a non-browser client; a wrong one is rejected.
    origin = ws.headers.get("origin", "")
    if AUTH_TOKEN and origin and origin not in _ALLOWED_ORIGINS:
        await ws.close(code=4403)
        return
    # The cookie carries a session id checked against the session table; ?token= is
    # the master token, for CLI clients.
    cookie_token = ws.cookies.get(AUTH_COOKIE_NAME, "") if hasattr(ws, "cookies") else ""
    authed = (cookie_token and _session_manager.check(cookie_token)) or _check_auth(token)
    if not authed:
        # The same bucket as the HTTP bootstrap; 4429 lets the client tell a rate limit
        # from an auth failure.
        over = _note_auth_fail(_client_ip(ws))
        await ws.close(code=4429 if over else 4401)
        return
    # Cap concurrent sessions — see MAX_WS_CONNECTIONS comment above.
    # `global` is declared once here; the finally block reuses the binding.
    global _ws_active_connections  # noqa: PLW0603 — module-level counter
    with _ws_connection_lock:
        if _ws_active_connections >= MAX_WS_CONNECTIONS:
            await ws.close(code=4429)  # 4429 = custom "too many connections"
            return
        _ws_active_connections += 1
    # A failed accept must release the reserved slot, or the counter drifts up until
    # MAX_WS_CONNECTIONS locks everyone out.
    try:
        await ws.accept()
    except Exception:
        with _ws_connection_lock:
            _ws_active_connections = max(0, _ws_active_connections - 1)
        raise

    briefing = get_briefing()
    session_id = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
    messages   = [_agent.make_message("system", build_system_prompt(briefing), authoritative=True)]
    stop_event = asyncio.Event()

    # check CS
    try:
        r = cs_request("GET", "/health", timeout=2)
        cs_ok = r.ok
    except Exception:
        cs_ok = False

    await ws.send_json({"type": "status", "content": "CS online" if cs_ok else "CS offline"})
    await ws.send_json({"type": "session_id", "id": session_id})

    # queue for incoming WebSocket messages
    ws_queue = asyncio.Queue()
    # Pending ASK prompts waiting on user approval, keyed by tc_id → Future.
    ask_waiters: dict[str, asyncio.Future] = {}

    async def _ws_reader():
        """Read WebSocket messages in the background."""
        try:
            while True:
                data = await ws.receive_json()
                t = data.get("type")
                if t == "stop":
                    stop_event.set()
                elif t == "tool_ask_response":
                    # A confirmation arriving mid-loop resolves the pending Future rather than
                    # re-queueing.
                    tc_id = data.get("id", "")
                    fut = ask_waiters.pop(tc_id, None)
                    if fut is not None and not fut.done():
                        fut.set_result(bool(data.get("allow", False)))
                else:
                    await ws_queue.put(data)
        except WebSocketDisconnect:
            # Cancel any outstanding ASK waiters so the main loop doesn't
            # hang waiting for a user who has left the page.
            for fut in ask_waiters.values():
                if not fut.done():
                    fut.set_result(False)
            ask_waiters.clear()
            await ws_queue.put(None)

    reader_task = asyncio.create_task(_ws_reader())

    # Whichever credential authenticated this socket, so the main loop re-verifies
    # it per message: a revoked session or a rotated token drops the socket.
    ws_auth_cookie = cookie_token
    ws_auth_token  = token if not cookie_token else ""

    try:
        while True:
            data = await ws_queue.get()
            if data is None:
                break

            # Re-checked on every inbound message, so a revoked session or rotated token
            # drops the socket within one turn.
            if AUTH_TOKEN:
                if ws_auth_cookie:
                    ok = _session_manager.check(ws_auth_cookie)
                elif ws_auth_token:
                    ok = _check_auth(ws_auth_token)
                else:
                    ok = False
                if not ok:
                    await ws.send_json({"type": "error", "content": "Session expired"})
                    await ws.close(code=4401)
                    break

            if data.get("type") == "clear":
                messages = [_agent.make_message("system", build_system_prompt(get_briefing()), authoritative=True)]
                session_id = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
                await ws.send_json({"type": "session_id", "id": session_id})
                continue

            if data.get("type") == "load_session":
                old_id = data.get("session_id", "")
                loaded = _load_session_local(old_id)
                if loaded:
                    session_id = old_id
                    messages = [_agent.make_message("system", build_system_prompt(get_briefing()), authoritative=True)]
                    # limit to the last 10 messages so we don't overload the model
                    old_msgs = loaded.get("messages", [])
                    if len(old_msgs) > 10:
                        old_msgs = old_msgs[-10:]
                    messages.extend(old_msgs)
                    await ws.send_json({"type": "session_loaded", "session": loaded})
                else:
                    await ws.send_json({"type": "error", "content": f"Session {old_id} not found"})
                continue

            if data.get("type") != "message":
                continue

            stop_event.clear()

            user_text = data.get("content", "").strip()
            think     = data.get("think", False)
            if not user_text:
                continue

            # Defense-in-depth: cap message size to prevent abuse / memory exhaustion
            if len(user_text) > WS_MAX_MESSAGE_CHARS:
                await ws.send_json({
                    "type": "error",
                    "content": f"Message too long ({len(user_text)} chars, limit {WS_MAX_MESSAGE_CHARS}). Truncated."
                })
                user_text = user_text[:WS_MAX_MESSAGE_CHARS]

            # Real user chat turn — authoritative.
            messages.append(_agent.make_message("user", user_text, authoritative=True))
            await ws.send_json({"type": "start"})

            # agent loop z WebSocket streaming
            loop_count = 0
            error_sent = False
            while loop_count < _agent.MAX_TOOL_LOOPS:
                loop_count += 1

                # Re-checked between tool iterations, so a revoke mid-turn stops the agent
                # within one tool call rather than at end of turn.
                if AUTH_TOKEN:
                    if ws_auth_cookie:
                        _ok = _session_manager.check(ws_auth_cookie)
                    elif ws_auth_token:
                        _ok = _check_auth(ws_auth_token)
                    else:
                        _ok = False
                    if not _ok:
                        stop_event.set()
                        await ws.send_json({"type": "error",
                                            "content": "Session expired mid-turn"})
                        error_sent = True
                        break

                # context compression
                if should_compact(messages, _agent.CONTEXT_MAX_TOKENS):
                    messages = compact_messages(
                        messages, OLLAMA_URL, OLLAMA_MODEL,
                        keep_last=6, max_tokens=_agent.CONTEXT_MAX_TOKENS
                    )
                    await ws.send_json({"type": "status", "content": f"[kompresja kontekstu]"})

                # streaming delta przez WebSocket
                full_content = ""
                tool_calls   = []
                collected    = {"content": "", "tc": []}

                # call Ollama streaming (in a thread pool so asyncio is not blocked)
                payload = {
                    "model":    OLLAMA_MODEL,
                    "messages": messages,
                    "tools":    TOOLS,
                    "stream":   True,
                    "think":    think,
                    "options":  {"temperature": 0.7, "num_ctx": int(os.getenv("NUM_CTX", "32768"))}
                }

                queue = asyncio.Queue()

                def _stream_ollama():
                    """Synchronous streaming on a separate thread — chunks into the queue."""
                    try:
                        resp = requests.post(
                            f"{OLLAMA_URL}/api/chat",
                            json=payload, stream=True, timeout=300
                        )
                        resp.raise_for_status()
                        for line in resp.iter_lines():
                            if stop_event.is_set():
                                resp.close()
                                queue.put_nowait({"_stopped": True})
                                return
                            if not line:
                                continue
                            try:
                                chunk = json.loads(line)
                            except Exception:
                                continue
                            queue.put_nowait(chunk)
                            if chunk.get("done"):
                                break
                    except Exception as e:
                        queue.put_nowait({"_error": str(e)})
                    finally:
                        queue.put_nowait(None)  # sentinel

                loop = asyncio.get_event_loop()
                loop.run_in_executor(None, _stream_ollama)

                # konsumuj chunks async
                stopped = False
                while True:
                    chunk = await queue.get()
                    if chunk is None:
                        break
                    if "_stopped" in chunk:
                        stopped = True
                        break
                    if "_error" in chunk:
                        await ws.send_json({"type": "error", "content": f"Ollama: {chunk['_error']}"})
                        error_sent = True
                        break

                    msg = chunk.get("message", {})

                    # thinking tokens
                    thinking_delta = msg.get("thinking", "")
                    if thinking_delta:
                        await ws.send_json({"type": "thinking_delta", "content": thinking_delta})

                    delta = msg.get("content", "")
                    if delta:
                        collected["content"] += delta
                        await ws.send_json({"type": "delta", "content": delta})

                    if msg.get("tool_calls"):
                        collected["tc"].extend(msg["tool_calls"])

                    if chunk.get("done"):
                        break

                if error_sent or stopped:
                    if stopped and collected["content"]:
                        # Partial assistant turn from a stop-button interrupt
                        # — still authoritative (model actually produced it).
                        messages.append(_agent.make_message(
                            "assistant",
                            collected["content"] + "\n[przerwano]",
                            authoritative=True,
                        ))
                    break

                tool_calls = collected["tc"]
                full_content = collected["content"]

                if not tool_calls:
                    # Final model response — authoritative.
                    messages.append(_agent.make_message("assistant", full_content, authoritative=True))
                    break

                # Assistant turn with tool_calls — authoritative, with the
                # tool_calls field attached post-construction (non-content).
                _asst = _agent.make_message("assistant", full_content, authoritative=True)
                _asst["tool_calls"] = tool_calls  # non-content field; the message role already went through make_message above
                messages.append(_asst)

                tool_results = []
                for i, tc in enumerate(tool_calls):
                    fn   = tc.get("function", {})
                    name = fn.get("name", "")
                    raw_args = fn.get("arguments", {})
                    if isinstance(raw_args, dict):
                        args = raw_args
                    else:
                        try:
                            args = json.loads(raw_args)
                        except (json.JSONDecodeError, TypeError):
                            args = {}

                    tc_id = f"{session_id}_{loop_count}_{i}"
                    arg_preview = args.get("command") or args.get("path") or args.get("content","")[:40] or ""

                    # Rejected before the policy check: the model can emit anything into
                    # function.name.
                    if not _valid_tool_name(name):
                        await ws.send_json({
                            "type": "tool_call",
                            "name": "[INVALID]",
                            "arg": f"rejected tool name: {str(name)[:80]}",
                            "id": tc_id,
                        })
                        tool_results.append(_agent.make_tool_result(
                            "invalid", "[ZABLOKOWANE] Invalid tool name",
                            source="invalid_name",
                        ))
                        continue

                    # Policy check
                    decision, reason = _policy.check(name, args)
                    if decision == PolicyDecision.DENY:
                        await ws.send_json({"type": "tool_call", "name": f"[DENY] {name}", "arg": reason, "id": tc_id})
                        tool_results.append(_agent.make_tool_result(
                            name, f"[ZABLOKOWANE] {reason}",
                            source="policy_deny",
                        ))
                        continue

                    if decision == PolicyDecision.ASK:
                        # A real confirmation over the WebSocket; auto-approval here would defeat the
                        # policy engine in web mode.
                        loop = asyncio.get_event_loop()
                        fut: asyncio.Future = loop.create_future()
                        ask_waiters[tc_id] = fut
                        await ws.send_json({
                            "type": "tool_ask",
                            "id": tc_id,
                            "name": name,
                            "arg": arg_preview,
                            "reason": reason,
                            "timeout": TOOL_ASK_TIMEOUT,
                        })
                        try:
                            allow = await asyncio.wait_for(fut, timeout=TOOL_ASK_TIMEOUT)
                        except asyncio.TimeoutError:
                            allow = False
                            ask_waiters.pop(tc_id, None)
                        if not allow:
                            await ws.send_json({
                                "type": "tool_call",
                                "name": f"[DENIED-BY-USER] {name}",
                                "arg": arg_preview,
                                "id": tc_id,
                            })
                            tool_results.append(_agent.make_tool_result(
                                name, "[BLOCKED by user]",
                                source="user_reject",
                            ))
                            continue
                        # fall through — user approved, render normal tool_call
                        await ws.send_json({"type": "tool_call", "name": name, "arg": arg_preview, "id": tc_id})
                    else:
                        await ws.send_json({"type": "tool_call", "name": name, "arg": arg_preview, "id": tc_id})

                    # Run the tool in the thread pool.
                    result = await asyncio.get_event_loop().run_in_executor(
                        None, execute_tool, name, args
                    )

                    await ws.send_json({"type": "tool_result", "id": tc_id, "result": result[:300]})
                    tool_results.append(_agent.make_tool_result(name, result))

                messages.extend(tool_results)

            await ws.send_json({"type": "done"})

            # auto-save
            _save_session_local(session_id, messages)
            save_session_to_cs(session_id, messages)

    except (WebSocketDisconnect, Exception):
        stop_event.set()
        reader_task.cancel()
        save_session_to_cs(session_id, messages)
    finally:
        # Release the connection slot even if save_session_to_cs throws.
        with _ws_connection_lock:
            _ws_active_connections = max(0, _ws_active_connections - 1)

def _get_ram_gb() -> float:
    """Get available RAM in GB."""
    try:
        with open("/proc/meminfo") as f:
            for line in f:
                if line.startswith("MemTotal:"):
                    kb = int(line.split()[1])
                    return kb / 1024 / 1024
    except Exception:
        pass
    return 0

def _model_fits(param_size_str: str, ram_gb: float) -> str:
    """Check if the model fits in RAM. Returns: ok/slow/no."""
    try:
        # parsuj rozmiar: "31.3B" -> 31.3, "7B" -> 7
        num = float(param_size_str.replace("B", "").strip())
    except (ValueError, AttributeError):
        return "unknown"
    # heuristic: model needs ~1.2x parameter count in GB of RAM (Q4 quantization)
    ram_needed = num * 0.6  # Q4_K_M: ~0.6 GB per billion params
    available = ram_gb * 0.75  # zostaw 25% na system
    if ram_needed <= available:
        return "ok"
    elif ram_needed <= ram_gb:
        return "slow"  # fits but little RAM left for anything else
    return "no"

@app.get("/api/models")
async def list_models(request: Request,
                      _auth=Depends(_require_auth_dep)):
    """List Ollama models with capabilities and compatibility info."""
    ram_gb = _get_ram_gb()
    try:
        r = requests.get(f"{OLLAMA_URL}/api/tags", timeout=5)
        models = []
        for m in r.json().get("models", []):
            name = m["name"]
            param_size = m.get("details", {}).get("parameter_size", "?")
            # pobierz capabilities
            try:
                show = requests.post(f"{OLLAMA_URL}/api/show", json={"model": name}, timeout=5)
                caps = show.json().get("capabilities", [])
            except Exception:
                caps = []
            models.append({
                "name": name,
                "size": param_size,
                "tools": "tools" in caps,
                "thinking": "thinking" in caps,
                "fit": _model_fits(param_size, ram_gb),
            })
        # sortuj: tools first, potem po rozmiarze
        models.sort(key=lambda x: (not x["tools"], x["name"]))
        return {"models": models, "current": OLLAMA_MODEL, "ram_gb": round(ram_gb, 1)}
    except Exception as e:
        return {"models": [], "current": OLLAMA_MODEL, "error": str(e)}

