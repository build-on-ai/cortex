def _check_auth(token: str) -> bool:
    """Constant-time token comparison. Empty AUTH_TOKEN disables auth."""
    if not AUTH_TOKEN:
        return True
    if not token:
        return False
    return secrets.compare_digest(token, AUTH_TOKEN)

